// Compiles src/tokens.json into dist/tokens.css (CSS custom properties).
//
// Layers:
//   primitive  raw values, emitted once on :root
//   styles.*   one visual style each (shape, borders, shadows, palette), chosen with
//              data-style="<name>" on <html>. The default style needs no attribute.
//     base     scheme-independent tokens (radius, border widths, fonts, motion transforms)
//     light    light color scheme
//     dark     dark color scheme (system preference, or data-theme="dark")
//
// Values written as "{color.gray.900}" become var(--nl-color-gray-900).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PREFIX = "nl";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function flatten(obj, path = []) {
  return Object.entries(obj).flatMap(([key, value]) =>
    typeof value === "object" && value !== null
      ? flatten(value, [...path, key])
      : [[[...path, key].join("-"), value]],
  );
}

export function resolveRef(value) {
  return value.replace(/\{([^}]+)\}/g, (_, ref) => `var(--${PREFIX}-${ref.replaceAll(".", "-")})`);
}

const toDeclarations = (obj, indent) =>
  flatten(obj)
    .map(([name, value]) => `${indent}--${PREFIX}-${name}: ${resolveRef(String(value))};`)
    .join("\n");

// Selectors that match an element using a given style. The default style also
// matches when no data-style attribute is set. Styles never overlap, so rule
// order across styles does not matter.
function styleSelectors(name, defaultStyle) {
  const list = [`[data-style="${name}"]`];
  if (name === defaultStyle) list.unshift(":root:not([data-style])");
  return list;
}

export function buildCss(tokens) {
  const { primitive, styles, defaultStyle } = tokens;
  const blocks = [`/* Generated by scripts/build.mjs. Do not edit. */\n:root {\n${toDeclarations(primitive, "  ")}\n}`];

  for (const [name, style] of Object.entries(styles)) {
    const sels = styleSelectors(name, defaultStyle);
    const join = (list) => list.join(",\n");
    blocks.push(
      `/* style: ${name} */\n${join(sels)} {\n${toDeclarations(style.base, "  ")}\n}`,
      `${join(sels)} {\n${toDeclarations(style.light, "  ")}\n  color-scheme: light;\n}`,
      `@media (prefers-color-scheme: dark) {\n${join(sels.map((s) => `  ${s}:not([data-theme="light"])`))} {\n${toDeclarations(style.dark, "    ")}\n    color-scheme: dark;\n  }\n}`,
      `${join(sels.map((s) => `${s}[data-theme="dark"]`))} {\n${toDeclarations(style.dark, "  ")}\n  color-scheme: dark;\n}`,
    );
  }
  return `${blocks.join("\n\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(readFileSync(join(root, "src/tokens.json"), "utf8"));
  mkdirSync(join(root, "dist"), { recursive: true });
  writeFileSync(join(root, "dist/tokens.css"), buildCss(tokens));
  writeFileSync(join(root, "dist/tokens.json"), JSON.stringify(tokens, null, 2));
  console.log("tokens: wrote dist/tokens.css");
}
